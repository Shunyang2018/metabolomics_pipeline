"""Portable HTML summaries for inspecting a reproducible pipeline run."""

from __future__ import annotations

import json
from html import escape
from pathlib import Path

import pandas as pd


def write_report(
    table: pd.DataFrame, manifest: dict, output: Path, *, synthetic: bool = False
) -> None:
    """Write a self-contained, escaped report with no external assets or scripts."""
    summary = manifest["merge"]
    stages = [
        ("Input features", summary["totals"]["raw"]),
        ("MS/MS filter", summary["totals"]["after_msms"]),
        ("S/N filter", summary["totals"]["after_snr"]),
        ("Blank/presence QC", summary["totals"]["after_pass"]),
        ("After deduplication", summary["rows"]),
    ]
    max_count = max([n for _, n in stages] + [1])
    bars = "".join(
        f'<tr><th>{escape(label)}</th><td><div class="bar" style="width:{100 * n / max_count:.1f}%">{n}</div></td></tr>'
        for label, n in stages
    )
    cols = [
        c
        for c in [
            "feature_id",
            "source_file",
            "Alignment ID",
            "Metabolite name",
            "annotation_level",
            "Average Mz",
            "mode",
        ]
        if c in table.columns
    ]
    preview = table[cols].head(20).to_html(index=False, escape=True, border=0)
    notice = (
        "Synthetic demonstration. Signals, spectra, taxonomy labels and reference matches are "
        "illustrative; they provide no evidence of compound identity or biological activity. "
        "SIRIUS inputs are exported, but SIRIUS predictions are not simulated or run."
        if synthetic
        else "Annotation levels are pipeline score categories, not standard-confirmed identifications. "
        "Reference matches require independent chemical and biological validation."
    )
    payload = escape(json.dumps(manifest, indent=2, ensure_ascii=False))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Metabolomics Pipeline — Run report</title><style>
body{{margin:0;background:#f3f6fa;color:#17283d;font:16px/1.6 system-ui,sans-serif}}
main{{max-width:1080px;margin:auto;padding:48px 24px}}header{{border-top:5px solid #16877e}}
h1{{font-size:clamp(30px,5vw,46px);line-height:1.15;margin:24px 0 12px}}h2{{margin-top:0}}
.eyebrow{{letter-spacing:.15em;font-size:12px;font-weight:700;color:#176c66}}
.notice{{border-left:4px solid #cf9f3b;background:#fff7e5;padding:16px 20px}}
section{{background:white;border:1px solid #dbe3ed;border-radius:12px;padding:24px;margin:24px 0;overflow:auto}}
table{{border-collapse:collapse;width:100%;font-size:14px}}th,td{{text-align:left;padding:10px;border-bottom:1px solid #e4eaf1}}
th{{white-space:nowrap}}.flow th{{width:190px}}.flow td{{width:65%}}.bar{{box-sizing:border-box;min-width:26px;background:#167d78;color:white;border-radius:4px;padding:3px 8px}}
pre{{white-space:pre-wrap;overflow-wrap:anywhere;font:12px/1.6 ui-monospace,monospace}}
footer{{color:#56667a;font-size:13px}}
</style></head><body><main><header><p class="eyebrow">SCIENTIFIC DATA WORKFLOW</p>
<h1>Metabolomics Pipeline</h1><p>MS-DIAL post-processing · quality control · annotation integration</p></header>
<p class="notice">{escape(notice)}</p>
<section><h2>Feature retention</h2><p>{summary["files"]} input tables · {len(table)} retained features ·
{manifest.get("bioactivity", {}).get("unique_features_matched", 0)} features with illustrative reference matches</p>
<table class="flow">{bars}</table></section>
<section><h2>Retained feature preview</h2><p>First 20 rows. source_file + Alignment ID preserve the input mapping;
feature_id is local to this run.</p>{preview}</section>
<section><h2>Reproduction record</h2><p>Input SHA-256 hashes, effective thresholds, software versions and stage counts.</p>
<details><summary>View manifest</summary><pre>{payload}</pre></details></section>
<footer>Generated by Metabolomics Pipeline. Review complete CSV outputs alongside this summary.</footer>
</main></body></html>""",
        encoding="utf-8",
    )
